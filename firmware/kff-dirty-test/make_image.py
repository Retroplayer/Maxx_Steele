"""Generate A000-BFFF ROM; optional --image accepts an exact 8KiB replacement."""
import argparse
from pathlib import Path
p=argparse.ArgumentParser();p.add_argument('--image',type=Path);a=p.parse_args()
b=bytearray([0xff]*8192)
b[:6]=bytes.fromhex('06 A0 28 63 29 20')
# SEI; CLD; set BCD $24/$25=1234; call stock display; NOP; JMP A014 forever.
code=bytes.fromhex('78 D8 A9 34 85 24 A9 12 85 25 20 D6 F6 EA 4C 14 A0')
b[6:6+len(code)]=code
if a.image:
 b=bytearray(a.image.read_bytes())
 if len(b)!=8192:p.error('image must be exactly 8192 bytes at A000-BFFF')
Path('test-cart.bin').write_bytes(b)
Path('image.h').write_text('/* Generated by make_image.py. */\nstatic const uint8_t boot_image[8192] = {\n'+''.join(' '+','.join(f'0x{x:02x}' for x in b[i:i+16])+',\n' for i in range(0,len(b),16))+'};\n')
